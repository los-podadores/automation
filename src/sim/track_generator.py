class ProceduralTrackGenerator:
    """Modular procedural generator synthesizing composable track zones."""

    def __init__(self, default_road_width: float = DEFAULT_ROAD_WIDTH) -> None:
        self.default_road_width = default_road_width

    def _catmull_rom_spline(
        self, control_pts: np.ndarray, total_points: int
    ) -> np.ndarray:
        """Compute smooth Catmull-Rom spline passing exactly through control points."""
        if len(control_pts) < 4:
            pts = np.vstack(
                [control_pts[0], control_pts, control_pts[-1], control_pts[-1]]
            )
        else:
            pts = np.vstack([control_pts[0], control_pts, control_pts[-1]])

        curve: list[np.ndarray] = []
        n_segs = len(pts) - 3
        pts_per_seg = max(4, total_points // n_segs)

        for i in range(n_segs):
            p0, p1, p2, p3 = pts[i : i + 4]
            for u in np.linspace(0.0, 1.0, pts_per_seg, endpoint=False):
                u2 = u * u
                u3 = u2 * u
                pt = 0.5 * (
                    (2.0 * p1)
                    + (-p0 + p2) * u
                    + (2.0 * p0 - 5.0 * p1 + 4.0 * p2 - p3) * u2
                    + (-p0 + 3.0 * p1 - 3.0 * p2 + p3) * u3
                )
                curve.append(pt)

        curve.append(pts[-2])
        return np.array(curve, dtype=np.float32)

    def _build_track_from_zones(
        self,
        zones: list[TrackZone],
        seed: int,
        preset_name: str,
        rng: np.random.Generator,
    ) -> ProceduralTrack:
        """Chain zones sequentially with C^1 heading continuity."""
        curr_x, curr_y = 0.0, 0.0
        curr_heading = 0.0

        all_centerline: list[np.ndarray] = []
        all_left_walls: list[tuple[float, float]] = []
        all_right_walls: list[tuple[float, float]] = []
        all_half_widths: list[float] = []
        all_wall_loops: list[list[tuple[float, float]]] = []
        all_obstacles: list[SimulatedEntity] = []
        total_length = 0.0


        for zone in zones:
            res = zone.generate(curr_x, curr_y, curr_heading, rng)
            all_centerline.append(res.centerline_pts)
            all_left_walls.extend(res.left_wall_pts)
            all_right_walls.extend(res.right_wall_pts)
            all_obstacles.extend(res.obstacles)
            hw_list = res.half_widths
            if hw_list is None:
                hw_list = [self.default_road_width / 2.0] * len(res.centerline_pts)
            all_half_widths.extend(hw_list)
            all_wall_loops.extend(res.wall_loops or [])
            curr_x = res.exit_x
            curr_y = res.exit_y
            curr_heading = res.exit_heading
            total_length += res.length

        # Combine centerline points without corner-cutting decimation
        raw_pts = np.vstack(all_centerline)
        diffs = np.linalg.norm(np.diff(raw_pts, axis=0), axis=1)
        keep_mask = np.concatenate(([True], diffs > 1e-4))
        clean_pts = raw_pts[keep_mask]

        # Resample along cumulative arc length with uniform 0.4m spacing
        seg_lens = np.linalg.norm(np.diff(clean_pts, axis=0), axis=1)
        cum_dists = np.concatenate(([0.0], np.cumsum(seg_lens)))
        total_dist = float(cum_dists[-1])
        target_pts_count = max(80, int(round(total_dist / 0.4)) + 1)
        s_query = np.linspace(0.0, total_dist, target_pts_count)
        xs = np.interp(s_query, cum_dists, clean_pts[:, 0]).astype(np.float32)
        ys = np.interp(s_query, cum_dists, clean_pts[:, 1]).astype(np.float32)
        clean_hw = np.asarray(all_half_widths, dtype=np.float64)[keep_mask]
        corridor_half_widths = np.interp(s_query, cum_dists, clean_hw).astype(np.float32)

        dxs = np.gradient(xs)
        dys = np.gradient(ys)
        yaws = np.arctan2(dys, dxs).astype(np.float32)

        waypoints_forward = np.column_stack([xs, ys, yaws]).astype(np.float32)

        # Reverse trajectory: Point B -> Point A
        rev_xs = np.flip(xs)
        rev_ys = np.flip(ys)
        rev_dxs = np.gradient(rev_xs)
        rev_dys = np.gradient(rev_ys)
        rev_yaws = np.arctan2(rev_dys, rev_dxs)
        waypoints_reverse = np.column_stack([rev_xs, rev_ys, rev_yaws]).astype(
            np.float32
        )

        start_pose = (float(xs[0]), float(ys[0]), float(yaws[0]))
        goal_pose = (float(xs[-1]), float(ys[-1]), float(yaws[-1]))

        # Assemble wall segments
        wall_segments: list[tuple[tuple[float, float], tuple[float, float]]] = []

        # Downsample wall points to prevent over-segmentation
        step_wall = 3
        has_paired_walls = bool(all_left_walls) and bool(all_right_walls)
        if has_paired_walls:
            l_sampled = all_left_walls[::step_wall]
            if not np.allclose(l_sampled[-1], all_left_walls[-1]):
                l_sampled.append(all_left_walls[-1])
            for i in range(len(l_sampled) - 1):
                wall_segments.append((l_sampled[i], l_sampled[i + 1]))

            r_sampled = all_right_walls[::step_wall]
            if not np.allclose(r_sampled[-1], all_right_walls[-1]):
                r_sampled.append(all_right_walls[-1])
            for i in range(len(r_sampled) - 1):
                wall_segments.append((r_sampled[i], r_sampled[i + 1]))

        for loop in all_wall_loops:
            if len(loop) < 2:
                continue
            sampled = loop[::step_wall]
            if not np.allclose(sampled[-1], loop[-1]):
                sampled.append(loop[-1])
            for i in range(len(sampled) - 1):
                wall_segments.append((sampled[i], sampled[i + 1]))
            # No closing edge: yard loops intentionally leave the entry gap open.

        # Enclosing back wall behind Point A
        if has_paired_walls:
            first_l, first_r = l_sampled[0], r_sampled[0]
        else:
            first_l = first_r = (float(xs[0]), float(ys[0]))
        first_px, first_py, first_psi = xs[0], ys[0], yaws[0]
        start_back_dist = 5.0
        start_cx = first_px - start_back_dist * math.cos(first_psi)
        start_cy = first_py - start_back_dist * math.sin(first_psi)
        start_hw = math.hypot(first_l[0] - first_px, first_l[1] - first_py)
        start_back_l = (
            float(start_cx - start_hw * math.sin(first_psi)),
            float(start_cy + start_hw * math.cos(first_psi)),
        )
        start_back_r = (
            float(start_cx + start_hw * math.sin(first_psi)),
            float(start_cy - start_hw * math.cos(first_psi)),
        )

        wall_segments.append((first_l, start_back_l))
        wall_segments.append((start_back_l, start_back_r))
        wall_segments.append((start_back_r, first_r))

        # Enclosing back wall behind Point B (skipped when a yard closes the track)
        if not zones[-1].closes_track:
            last_l = l_sampled[-1]
            last_r = r_sampled[-1]
            last_px, last_py, last_psi = xs[-1], ys[-1], yaws[-1]
            court_back_dist = 6.0
            back_cx = last_px + court_back_dist * math.cos(last_psi)
            back_cy = last_py + court_back_dist * math.sin(last_psi)
            hw = math.hypot(last_l[0] - last_px, last_l[1] - last_py)
            back_l = (
                float(back_cx - hw * math.sin(last_psi)),
                float(back_cy + hw * math.cos(last_psi)),
            )
            back_r = (
                float(back_cx + hw * math.sin(last_psi)),
                float(back_cy - hw * math.cos(last_psi)),
            )

            wall_segments.append((last_l, back_l))
            wall_segments.append((back_l, back_r))
            wall_segments.append((back_r, last_r))

        # Dynamic fair max episode calculation:
        # Distance = A -> B (total_length) + B -> A (total_length) + 15m buffer
        # At v_nominal = 1.5 m/s, dt = 0.05s, with 2.2x maneuver factor + 60 hold steps
        roundtrip_dist = 2.0 * total_length + 15.0
        max_steps = 60 + int((roundtrip_dist / 1.5) * (2.2 / 0.05))

        return ProceduralTrack(
            seed=seed,
            start_pose=start_pose,
            goal_pose=goal_pose,
            waypoints_forward=waypoints_forward,
            waypoints_reverse=waypoints_reverse,
            wall_segments=wall_segments,
            obstacles=all_obstacles,
            corridor_half_widths=corridor_half_widths,
            road_width=self.default_road_width,
            nominal_length=float(total_length),
            max_episode_steps=max_steps,
            preset_name=preset_name,
        )

    def generate_estadio_ho_chi_min(self, seed: int | None = None) -> ProceduralTrack:
        """Fixed site scenario: road A -> left turn -> rectangular yard B (1:1 meters)."""
        seed_val = int(seed) if seed is not None else 42
        rng = np.random.default_rng(seed_val)
        site = ESTADIO_SITE

        zones: list[TrackZone] = [
            StraightCorridorZone(
                length=site["road_length"],
                road_width=site["road_width"],
                num_obstacles=5,
                num_dynamic_peds=2,
            ),
            TurnCorridorZone(
                turn_angle_rad=math.pi / 2.0,
                radius=site["turn_radius"],
                road_width=site["road_width"],
            ),
            RectangularYardZone(
                length=site["yard_length"],
                width=site["yard_width"],
                road_width=site["road_width"],
                entry_width=site["entry_width"],
                entry_offset=site["entry_offset"],
                yard_heading=None,
                goal_margin=site["goal_margin"],
                num_static_obstacles=5,
                num_dynamic_peds=2,
            ),
        ]
        return self._build_track_from_zones(zones, seed_val, "estadio_ho_chi_min", rng)

    def generate_random_track(
        self,
        seed: int | None = None,
        min_length: float = 110.0,
        max_length: float = 160.0,
    ) -> ProceduralTrack:
        """Procedurally synthesize a randomized multi-zone track within target length range."""
        seed_val = (
            int(seed)
            if seed is not None
            else int(np.random.default_rng().integers(0, 1_000_000))
        )
        rng = np.random.default_rng(seed_val)

        target_length = float(rng.uniform(min_length, max_length))
        current_len = 0.0

        zones: list[TrackZone] = [
            # Initial straight departure
            StraightCorridorZone(
                length=float(rng.uniform(20.0, 30.0)),
                road_width=self.default_road_width,
                num_obstacles=int(rng.integers(2, 4)),
                num_dynamic_peds=int(rng.integers(1, 3)),
            )
        ]
        current_len += 25.0

        # Available intermediate zone types
        while current_len < (target_length - 20.0):
            zone_choice = rng.choice(["turn", "yard", "straight"])
            if zone_choice == "turn":
                # -90 deg, +90 deg, or 45-60 deg turns
                turn_deg = float(rng.choice([-90.0, 90.0, -60.0, 60.0, -45.0, 45.0]))
                turn_rad = math.radians(turn_deg)
                r_turn = float(rng.uniform(7.5, 9.5))
                zones.append(
                    TurnCorridorZone(
                        turn_angle_rad=turn_rad,
                        radius=r_turn,
                        road_width=self.default_road_width,
                    )
                )
                current_len += abs(turn_rad) * r_turn
            elif zone_choice == "yard":
                y_len = float(rng.uniform(30.0, 45.0))
                y_w = float(rng.uniform(25.0, 35.0))
                zones.append(
                    RectangularYardZone(
                        length=y_len,
                        width=y_w,
                        road_width=self.default_road_width,
                        entry_offset=0.0,
                        yard_heading=None,
                        num_static_obstacles=int(rng.integers(3, 6)),
                        num_dynamic_peds=int(rng.integers(1, 3)),
                    )
                )
                current_len += y_len
                break  # yard closes the track: terminal zone only
            else:
                s_len = float(rng.uniform(20.0, 35.0))
                zones.append(
                    StraightCorridorZone(
                        length=s_len,
                        road_width=self.default_road_width,
                        num_obstacles=rng.integers(2, 5),
                        num_dynamic_peds=int(rng.integers(1, 3)),
                    )
                )
                current_len += s_len

        return self._build_track_from_zones(zones, seed_val, "random", rng)

    def generate_track(
        self,
        seed: int | None = None,
        length: float = 95.0,
        road_width: float | None = None,
        num_obstacles: int = 4,
        preset: str = DEFAULT_PRESET,
    ) -> ProceduralTrack:
        """Public generation entry point supporting presets or custom random generation."""
        if road_width is not None:
            self.default_road_width = road_width

        if preset == "estadio_ho_chi_min":
            return self.generate_estadio_ho_chi_min(seed=seed)
        elif preset == "random":
            return self.generate_random_track(
                seed=seed, min_length=length * 0.9, max_length=length * 1.3
            )
        else:
            raise ValueError(
                f"Unknown preset: '{preset}'. Valid presets are {list(PRESETS)}."
            )
